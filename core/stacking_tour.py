def show_settings_tour(owner, dialog, tabs, fields, autosave_button):
    targets = {**fields, 'settings_menu': tabs.tabBar(), 'autosave': autosave_button}
    introductions = (
        ('Сложение', 'Integration', 'Здесь задаются метод объединения кадров и обработка фона результата.', 'Choose the frame combination method and configure background processing here.'),
        ('Отбор кадров', 'Frame selection', 'Эта вкладка управляет проверкой качества и долей кадров для сложения.', 'Configure quality checks and the percentage of frames used for stacking.'),
        ('Совмещение', 'Registration', 'Здесь настраиваются поиск звёзд, совмещение и общая область результата.', 'Configure star detection, registration and the common output area here.'),
        ('Калибровка', 'Calibration', 'Здесь задаются параметры мастер-кадров и исправления дефектных пикселей.', 'Configure master frames and defective pixel correction here.'),
        ('Смаз', 'Motion', 'Эта вкладка управляет исправлением короткого прямолинейного смаза.', 'Configure short linear motion blur correction here.'),
        ('Drizzle', 'Drizzle', 'Здесь настраивается реконструкция изображения по субпиксельным сдвигам кадров.', 'Configure image reconstruction from subpixel frame offsets here.'),
        ('Ресурсы', 'Resources', 'Здесь выбираются режим вычислений и место хранения временных данных.', 'Choose the compute mode and temporary storage location here.'),
    )
    steps = []
    introduced = set()
    for key, title_ru, title_en, hint_ru, hint_en in SETTINGS_STEPS:
        target = targets[key]
        if key != 'settings_menu':
            index = next(i for i in range(tabs.count()) if tabs.widget(i).isAncestorOf(target))
            if index not in introduced:
                steps.append((tabs.widget(index), *introductions[index]))
                introduced.add(index)
        steps.append((target, title_ru, title_en, hint_ru, hint_en))
    InterfaceTour(owner, surface=dialog, steps=steps, tabs=tabs).start()
